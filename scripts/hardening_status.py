"""The hardening pass's per-tool status list (docs/hardening): one data file,
status.json, and the table generated from it, STATUS.md.

    python3 scripts/hardening_status.py mark sketch_new,sketch_add --docs --health --description --headless --live --model SketcherTutorial --note "…"
    python3 scripts/hardening_status.py render      # rewrite STATUS.md
    python3 scripts/hardening_status.py bars        # the counts as bars

A flag is only set by something that was done and measured: docs (checked
against FreeCAD's wiki and source), health (the shared health check seen on
its answer, or a read that needs none), description (rewritten), headless
(proven through the MCP tools on a test model), live (proven in the FreeCAD
window), model (the test model that proved it).
"""
import json
import os
import sys

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "hardening")
INV, STATUS, TABLE = (os.path.join(HERE, n) for n in ("inventory.json", "status.json", "STATUS.md"))
FLAGS = ("docs", "health", "description", "headless", "live")


def load():
    with open(INV, encoding="utf-8") as f:
        groups = json.load(f)["groups"]
    status = {}
    if os.path.isfile(STATUS):
        with open(STATUS, encoding="utf-8") as f:
            status = json.load(f)
    return groups, status


def save(status):
    with open(STATUS, "w", encoding="utf-8") as f:
        json.dump(status, f, indent=1, sort_keys=True)
        f.write("\n")


def bar(n, total, width=20):
    k = round(width * n / total) if total else 0
    return "█" * k + "░" * (width - k)


def counts(groups, status):
    tools = [(t, g, d["workbench"]) for g, d in groups.items() for t in d["tools"]]
    total = len(tools)
    out = {f: sum(1 for t, _g, _w in tools if status.get(t, {}).get(f)) for f in FLAGS}
    out["proven"] = sum(1 for t, _g, _w in tools if status.get(t, {}).get("headless") or status.get(t, {}).get("live"))
    return total, out, tools


def bars(groups, status):
    total, c, tools = counts(groups, status)
    lines = ["Per-tool status (measured: counted from docs/hardening/status.json)"]
    for key, label in (("proven", "proven on a test model"), ("headless", "  headless"), ("live", "  live in the window"), ("docs", "docs checked"),
                       ("health", "health check seen"), ("description", "description rewritten")):
        lines.append(f"{label:<24}{bar(c[key], total)} {c[key]:>3}/{total}")
    lines.append("")
    lines.append("By workbench (tools proven / total)")
    order = []
    for _t, _g, w in tools:
        if w not in order:
            order.append(w)
    for w in order:
        mine = [t for t, _g, ww in tools if ww == w]
        n = sum(1 for t in mine if status.get(t, {}).get("headless") or status.get(t, {}).get("live"))
        lines.append(f"{w:<24}{bar(n, len(mine))} {n:>3}/{len(mine)}")
    return "\n".join(lines)


def render(groups, status):
    y = lambda v: "yes" if v else "–"  # noqa: E731
    out = ["# Hardening pass: per-tool status", "",
           "Generated by `scripts/hardening_status.py render` from `status.json` and `inventory.json`. Do not edit by hand.", "",
           "```", bars(groups, status), "```", ""]
    last = None
    for g, d in groups.items():
        if d["workbench"] != last:
            last = d["workbench"]
            out += [f"## {last}", ""]
        out += [f"### {g} ({d['repo']})", "", "| tool | docs | health | description | headless | live | model | note |", "|---|---|---|---|---|---|---|---|"]
        for t in d["tools"]:
            s = status.get(t, {})
            out.append(f"| `{t}` | {y(s.get('docs'))} | {y(s.get('health'))} | {y(s.get('description'))} | {y(s.get('headless'))} | {y(s.get('live'))} | {s.get('model', '')} | {s.get('note', '')} |")
        out.append("")
    with open(TABLE, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


def main(argv):
    groups, status = load()
    known = {t for d in groups.values() for t in d["tools"]}
    if argv[:1] == ["mark"] and len(argv) >= 2:
        names = [n for n in argv[1].split(",") if n]
        bad = [n for n in names if n not in known]
        if bad:
            sys.exit(f"not in the inventory: {', '.join(bad)}")
        rest = argv[2:]
        for n in names:
            s = status.setdefault(n, {})
            i = 0
            while i < len(rest):
                a = rest[i]
                if a.lstrip("-") in FLAGS:
                    s[a.lstrip("-")] = True
                elif a in ("--model", "--note") and i + 1 < len(rest):
                    i += 1
                    s[a[2:]] = rest[i]
                else:
                    sys.exit(f"unknown: {a}")
                i += 1
        save(status)
        render(groups, status)
    elif argv[:1] == ["render"]:
        render(groups, status)
    elif argv[:1] == ["bars"]:
        print(bars(groups, status))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
