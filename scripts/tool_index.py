"""agentlink/data/tool_index.json, generated: for every tool Agent Link
itself defines, FreeCAD's workbench, the FreeCAD commands it does the work
of, and search words its name lacks (agentlink/toolindex.py reads it for
tool_groups { find } and { now }).

The live echo's tables stay the source (agentlink/echo.py: WORKBENCH,
COMMAND, CAM_OP, CAM_DRESSUP, command_for); scripts/tool_index_more.py adds
by hand what the echo does not need. Tools are read from the source with
ast, so this runs in plain Python without FreeCAD. Add-ons' tools are not
here: an add-on gives the same fields in its own tools.json.

    python3 scripts/tool_index.py           # rewrite the file
    python3 scripts/tool_index.py --check   # exit 1 when it is stale
"""
import ast
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
PKG = os.path.join(ROOT, "agentlink")
OUT = os.path.join(PKG, "data", "tool_index.json")
sys.path.insert(0, ROOT)
sys.path.insert(0, HERE)

ABOUT = ("Each of Agent Link's own tools as FreeCAD files it: workbench (FreeCAD's workbench class name, null for none), "
         "commands (the FreeCAD commands the tool does the work of) and words (search words its name lacks). "
         "Generated by scripts/tool_index.py from agentlink/echo.py and scripts/tool_index_more.py: edit those, not this. "
         "Command names are FreeCAD's (1.1). An add-on gives the same three fields in its own tools.json entries.")


def tool_names():
    """Every tool defined here, in name order: Tool("name", …) calls in
    agentlink/ and agentlink/families/, and data/tools.json's entries."""
    names = set()
    for folder in (PKG, os.path.join(PKG, "families")):
        for f in sorted(os.listdir(folder)):
            if not f.endswith(".py"):
                continue
            with open(os.path.join(folder, f), encoding="utf-8") as fh:
                tree = ast.parse(fh.read())
            for node in ast.walk(tree):
                fn = getattr(node, "func", None)
                if isinstance(node, ast.Call) and (getattr(fn, "id", None) == "Tool" or getattr(fn, "attr", None) == "Tool"):
                    if node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                        names.add(node.args[0].value)
    with open(os.path.join(PKG, "data", "tools.json"), encoding="utf-8") as fh:
        names.update(json.load(fh)["entries"])
    return sorted(names)


def _longest(name, pairs):
    best, got = -1, None
    for k, v in pairs:
        if name.startswith(k) and len(k) > best:
            best, got = len(k), v
    return got


def entry(name, echo, more):
    wb = echo._workbench_for(name) or _longest(name, more.WORKBENCH.items())
    cmds = []
    first = echo.COMMAND.get(name)
    if first:
        cmds.append(first)
    for kind in more.KINDS.get(name, ()):
        cmds.append(echo.command_for(name, {"kind": kind}))
    if name == "cam_op":
        cmds += list(echo.CAM_OP.values())
    if name == "cam_dressup":
        cmds += list(echo.CAM_DRESSUP.values())
    extra, words = more.TOOLS.get(name, ([], ""))
    cmds += extra
    have = set(name.split("_"))
    ws = []
    for k, v in more.PREFIX_WORDS.items():
        if name.startswith(k):
            ws += v
    ws += words.split()
    return {"workbench": wb, "commands": list(dict.fromkeys(c for c in cmds if c)),
            "words": list(dict.fromkeys(w.lower() for w in ws if w.lower() not in have)),
            "source": more.SOURCE, "date": more.DATES.get(name, more.DATE)}


def build():
    from agentlink import echo

    import tool_index_more as more

    return {"$schema": "tool_index.schema.json", "dataVersion": "1.0.0", "licence": "CC-BY-4.0", "about": ABOUT,
            "entries": {n: entry(n, echo, more) for n in tool_names()}}


def render():
    """The file's text: one tool a line, so a change reads in a diff."""
    doc = build()
    head = {k: v for k, v in doc.items() if k != "entries"}
    lines = [json.dumps(head, ensure_ascii=False, indent=1)[:-2] + ",", ' "entries": {']
    rows = [f"  {json.dumps(n)}: {json.dumps(e, ensure_ascii=False)}" for n, e in doc["entries"].items()]
    lines.append(",\n".join(rows))
    lines += [" }", "}"]
    return "\n".join(lines) + "\n"


def main(argv):
    new = render()
    json.loads(new)
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                cur = f.read()
        except OSError:
            cur = ""
        if cur != new:
            sys.stderr.write("agentlink/data/tool_index.json is stale: run python3 scripts/tool_index.py\n")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
